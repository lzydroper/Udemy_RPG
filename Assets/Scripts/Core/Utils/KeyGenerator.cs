using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Core.Utils
{
    public static class KeyGenerator
    {
        public static void Generate(KeyDatabase database)
        {
            if (database == null)
            {
                Debug.LogError("KeyDatabase is null.");
                return;
            }

            var OutputPath = database.OutputPath;
            var Namespace = database.Namespace;
            EnsureDirectory(OutputPath);

            var sb = new StringBuilder();

            WriteHeader(sb, Namespace);

            foreach (var category in database.categories)
            {
                WriteCategory(sb, category);
            }

            WriteFooter(sb);

            File.WriteAllText(OutputPath, sb.ToString(), Encoding.UTF8);

            AssetDatabase.Refresh();

            Debug.Log($"keys.cs generated.\n{OutputPath}");
        }

        private static void WriteHeader(StringBuilder sb, string Namespace)
        {
            sb.AppendLine("//------------------------------------------------------------------------------");
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     This file is generated automatically.");
            sb.AppendLine("//     DO NOT MODIFY.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("//------------------------------------------------------------------------------");
            sb.AppendLine();

            sb.AppendLine($"namespace {Namespace}");
            sb.AppendLine("{");
            sb.AppendLine("    public static class Keys");
            sb.AppendLine("    {");
        }

        private static void WriteFooter(StringBuilder sb)
        {
            sb.AppendLine("    }");
            sb.AppendLine("}");
        }

        private static void WriteCategory(StringBuilder sb, KeyCategory category)
        {
            if (category == null)
                return;

            if (string.IsNullOrWhiteSpace(category.category))
                return;

            var className = MakeIdentifier(category.category);

            sb.AppendLine();
            sb.AppendLine($"        public static class {className}");
            sb.AppendLine("        {");

            foreach (var key in category.keys.Distinct())
            {
                if (string.IsNullOrWhiteSpace(key))
                    continue;

                var fieldName = MakeIdentifier(key);

                sb.AppendLine(
                    $"            public const string {fieldName} = \"{key}\";");
            }

            sb.AppendLine("        }");
        }

        /// <summary>
        /// 把字符串转换成合法C#标识符
        /// </summary>
        private static string MakeIdentifier(string value)
        {
            var sb = new StringBuilder();

            foreach (char c in value)
            {
                if (char.IsLetterOrDigit(c) || c == '_')
                {
                    sb.Append(c);
                }
                else
                {
                    sb.Append('_');
                }
            }

            if (sb.Length == 0)
                sb.Append('_');

            if (char.IsDigit(sb[0]))
                sb.Insert(0, '_');

            return sb.ToString();
        }

        private static void EnsureDirectory(string OutputPath)
        {
            var directory = Path.GetDirectoryName(OutputPath);

            if (Directory.Exists(directory))
                return;

            Directory.CreateDirectory(directory!);
        }
    }
}